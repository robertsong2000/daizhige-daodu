# 反向抽查：页面所有 class="sq" 元素内的引文
html = open(PAGE, encoding="utf-8").read()
blocks = re.findall(r'<(\w+)[^>]*class="sq"[^>]*>(.*?)</\1>', html, flags=re.S)
print(f"\n页面引文元素（class=sq）{len(blocks)} 个：")
for tag, b in blocks:
    body = re.sub(r"<[^>]+>", "", b)
    for seg in re.split(r"……|\.\.\.", body):
        seg = seg.strip()
        if seg:
            check(seg, "页面元素")

# 排版与依赖规则
for i, line in enumerate(html.split("\n"), 1):
    if "—" in line or "–" in line:
        print("FAIL 排版：出现长划线，行", i, line.strip()[:40]); fail += 1
    if line.count("·") > 1:
        print("FAIL 排版：一行多个·，行", i, line.strip()[:40]); fail += 1
if re.search(r'<script', html, re.I):
    print("FAIL 依赖：出现 script 标签"); fail += 1
if re.search(r'src\s*=', html, re.I):
    print("FAIL 依赖：出现外部 src"); fail += 1

# 锚点与页脚要件
for i in range(1, 11):
    if f'id="z{i}"' not in html:
        print("FAIL 缺少锚点 z%d" % i); fail += 1
    if f'href="#z{i}"' not in html:
        print("FAIL 缺少导航 z%d" % i); fail += 1
for k in ["殆知阁", "核验", "局限", "mulu.html", "daizhigev20"]:
    if k not in html:
        print("FAIL 页面缺少：", k); fail += 1

