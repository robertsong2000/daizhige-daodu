fail = 0
for q, where in QUOTES:
    ok = norm(q) in text
    print(("PASS" if ok else "FAIL"), where, q[:22] + ("…" if len(q) > 22 else ""))
    fail += 0 if ok else 1

# 页面所有 .q span 与 blockquote 引文块整体核验
html = open(PAGE, encoding="utf-8").read()
blocks = []
for m in re.finditer(r'<blockquote class="bq">(.*?)</blockquote>', html, re.S):
    body = re.sub(r'<span class="from">.*?</span>', "", m.group(1), flags=re.S)
    blocks.append(re.sub(r"<[^>]+>", "", body))
blocks.extend(re.sub(r"<[^>]+>", "", q) for q in re.findall(r'<span class="q">(.*?)</span>', html, re.S))
print(f"\n页面引文块 {len(blocks)} 个（blockquote + .q span）：")
for b in blocks:
    b = b.strip()
    if len(norm(b)) < 4:
        continue
    ok = norm(b) in text
    print(("PASS" if ok else "FAIL"), b[:26])
    fail += 0 if ok else 1

# 排版规则：禁止长划线；每行 · 至多 1 个
for i, line in enumerate(html.split("\n"), 1):
    if "—" in line or "–" in line:
        print("FAIL 排版：出现长划线，行", i)
        fail += 1
    if line.count("·") > 1:
        print("FAIL 排版：一行多个·，行", i, line.strip()[:40])
        fail += 1

# 硬性视觉：墨底、纸白、宋体族、无外部依赖
