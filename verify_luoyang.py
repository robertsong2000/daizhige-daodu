errs = []
def chk(cond, msg):
    if not cond: errs.append(msg)

def norm(s):
    out = []
    for ch in s:
        if ch.isspace(): continue
        o = ord(ch)
        if (0x3000 <= o <= 0x303F) or (0xFF00 <= o <= 0xFFEF and not (0xFF21 <= o <= 0xFF5A)) \
           or ch in '「」『』“”‘’·，。、；：？！〈〉《》()(){}[]<>' or (o < 0x2E80 and not ch.isalnum()) \
           or (0x2018 <= o <= 0x201F):
            continue
        out.append(ch)
    return ''.join(out)

