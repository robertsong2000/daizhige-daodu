def normalize(s: str) -> str:
    s = unicodedata.normalize("NFC", s)
    s = "".join(VARIANTS.get(c, c) for c in s)
    return re.sub(r"[\s　，。；：、「」『』（）【】《》！？“”‘’·…\-—–.,;:!?]+", "", s)

