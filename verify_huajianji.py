def norm(s):
    s = unicodedata.normalize('NFKC', s)
    for k, v in VARIANTS.items():
        s = s.replace(k, v)
    s = re.sub(r'\s+', '', s)
    s = re.sub(r'[，。！？；：、''""（）《》○△\[\]{}·…—–\-,.!?;:()<>「」『』]', '', s)
    return s

