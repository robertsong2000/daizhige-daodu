# 仅库内核验、页面不作展示引用的条目
LIB_ONLY = {'Q34 皇甫·浪涛沙其一', 'Q35 尹·目录数', 'Q41 目录·顾敻'}

fails = 0
for tag, q in quotes:
    nq = norm(q)
    if nq not in T:
        fails += 1
        print(f'✗ {tag}: 未命中')
        lo, hi = 0, len(nq)
        while lo < hi:
            mid = (lo + hi + 1) // 2
            if nq[:mid] in T:
                lo = mid
            else:
                hi = mid - 1
        print(f'   命中前 {lo} 字，断点附近: …{q[max(0,lo-10):lo]}【{q[lo:lo+12]}】…')
    else:
        print(f'✓ {tag}')

print()

# 第二轮：页面可见文本复核（页内引文不得转写失真）
import re as _re
page = open('/home/robertsong/workspace/claude/daizhige-daodu/huajianji.html').read()
body = page[page.index('<body>'):]
body = _re.sub(r'<(script|style)[^>]*>.*?</\1>', '', body, flags=_re.S)
body = _re.sub(r'<[^>]+>', '', body)   # 去标签，仅保留可见文本（含被拆分的 span 拼合）
P = norm(body)

pfails = 0
for tag, q in quotes:
    if tag in LIB_ONLY:
        continue
    if norm(q) not in P:
        pfails += 1
        print(f'✗ 页面缺或异: {tag}')
if pfails:
    print(f'页面复核失败 {pfails} 条'); sys.exit(1)
print(f'页面可见文本复核 {len(quotes)} 条全部命中')

# 版式红线：无长划线，每行至多一个间隔号
for i, ln in enumerate(page.split('\n'), 1):
    if '—' in ln or '–' in ln:
        print(f'✗ 第{i}行含长划线'); pfails += 1
    if ln.count('·') > 1:
        print(f'✗ 第{i}行间隔号超限: {ln.strip()[:40]}'); pfails += 1
if pfails:
    sys.exit(1)
print('版式红线检查通过：无长划线，间隔号每行至多一个')

if fails:
    print(f'库内核验失败 {fails} 条'); sys.exit(1)
print(f'库内 {len(quotes)} 条核验通过')
