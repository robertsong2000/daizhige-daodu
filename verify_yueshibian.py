def norm(s: str) -> str:
    s = unicodedata.normalize('NFKC', s)
    s = ''.join(NORM.get(c, c) for c in s)
    return re.sub(r'[^0-9A-Za-z一-鿿]', '', s)


def main() -> int:
    src = norm(open(SRC, encoding='utf-8').read())
    html_raw = open(HTML, encoding='utf-8').read()
    html = norm(re.sub(r'<[^>]+>', ' ', html_raw))
    fails = []
    for label, q in QUOTES:
        nq = norm(q)
        ok_src = nq in src
        ok_html = nq in html
        stat = 'OK ' if (ok_src and ok_html) else 'FAIL'
        print(f'{stat} [{label}] 源文件:{ok_src} 页面:{ok_html}')
        if not (ok_src and ok_html):
            fails.append(label)
    print(f'\n共 {len(QUOTES)} 条, 通过 {len(QUOTES)-len(fails)}')
    if fails:
        print('未通过:', '、'.join(fails)); return 1
    # 页面纪律:禁长划线;渲染后每行·最多1个
    for bad in ('—', '–'):
        if bad in html_raw:
            print(f'页面含禁用字符 {bad!r}'); return 1
    for line in html_raw.splitlines():
        vis = re.sub(r'<[^>]+>', '', line)
        if vis.count('·') > 1:
            print('一行内·超1个:', line.strip()[:60]); return 1
    print('页面纪律检查通过:无长划线,每行·不超1个')
    return 0


if __name__ == '__main__':
    sys.exit(main())
