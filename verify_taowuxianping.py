def main():
    src = norm(open(TXT).read())
    html = open(HTML).read()

    fail = 0
    for q in QUOTES:
        if norm(q) not in src:
            print('FAIL 库内无此句:', q[:30])
            fail += 1

    used = re.findall(r'「([^」]+)」', html)
    for u in used:
        if norm(u) not in src:
            print('FAIL 页面引文未过核验:', u[:40])
            fail += 1
        if not any(norm(u) == norm(q) for q in QUOTES):
            print('FAIL 页面引文不在清单内:', u[:40])
            fail += 1

    # 回目牌（楹联水牌）文本也必须逐字有据
    plaques = re.findall(r'<span class="ps">([^<]+)</span>', html)
    for p in plaques:
        if norm(p) not in src:
            print('FAIL 回目牌未过核验:', p)
            fail += 1

    print('清单引文 %d 条' % len(QUOTES))
    print('页面「」引文 %d 处，回目牌 %d 联' % (len(used), len(plaques)))
    if fail == 0:
        print('PASS 全部核验通过')
    else:
        print('FAIL 共 %d 处' % fail)
        sys.exit(1)

if __name__ == '__main__':
    main()
