# ---- 反扫页面：HTML 中所有含「」的引文块必须都能在源文件命中 ----
import os
if os.path.exists(PAGE):
    html = open(PAGE, encoding="utf-8").read()
    cites = re.findall(r"[「【]([^」】]{6,})[」】]", html)
    miss = 0
    for c in cites:
        q = norm(c)
        if q and q not in nei and q not in jin:
            print("PAGE-FAIL", c[:30])
            miss += 1
