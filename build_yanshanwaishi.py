# 四六拆对卡：先把上下半联各包成块级 half，再给对仗词上色（片段必须原样存在于库本）
HALVES = {
    'Q16': ('地老天荒，毕竟悲多欢少；', '海枯石烂，大都别易会难。'),
    'Q29': ('因匿灾而就毙，漠不上闻；', '即奉诏以赈荒，徒为中饱。'),
    'Q34': ('破纸窗中，风穿似弩；', '败苇帘外，雪大如鸦。'),
}
PAIRS = {
    'Q16': [('地老天荒', 'pa'), ('悲多欢少', 'pa'), ('海枯石烂', 'pb'), ('别易会难', 'pb')],
    'Q29': [('匿灾而就毙', 'pa'), ('漠不上闻', 'pa'), ('奉诏以赈荒', 'pb'), ('徒为中饱', 'pb')],
    'Q34': [('破纸窗中', 'pa'), ('风穿似弩', 'pa'), ('败苇帘外', 'pb'), ('雪大如鸦', 'pb')],
}

def build():
    src = open(SRC, encoding='utf-8').read()
    html = open(TPL, encoding='utf-8').read()
    for tok, a, b in QUOTES:
        ia = src.find(a)
        assert ia >= 0, f'{tok} start anchor not found: {a}'
        assert src.find(a, ia + 1) == -1, f'{tok} start anchor not unique: {a}'
        ib = src.find(b, ia)
        assert ib >= 0, f'{tok} end anchor not found: {b}'
        text = src[ia:ib + len(b)]
        if tok in HALVES:
            up, low = HALVES[tok]
            assert text == up + low, f'{tok} halves mismatch: {text!r}'
            text = f'<s class="half ha">{up}</s><s class="half hb">{low}</s>'
        for frag, cls in PAIRS.get(tok, []):
            assert text.count(frag) == 1, f'{tok} pair frag bad: {frag}'
            text = text.replace(frag, f'<s class="{cls}">{frag}</s>')
        token = '{{' + tok + '}}'
        assert token in html, f'token missing in tpl: {token}'
        html = html.replace(token, text)
    leftover = html.find('{{Q')
    assert leftover == -1, f'unreplaced token at {leftover}'
    open(OUT, 'w', encoding='utf-8').write(html)
    print(f'OK {len(QUOTES)} quotes injected -> {OUT} ({os.path.getsize(OUT)} bytes)')

if __name__ == '__main__':
    build()
