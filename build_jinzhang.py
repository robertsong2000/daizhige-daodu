def slice_quote(src, start, end):
    ia = src.find(start)
    assert ia >= 0, f'start anchor not found: {start}'
    ib = src.find(end, ia)
    assert ib >= 0, f'end anchor not found after start: {end}'
    return src[ia:ib + len(end)]


def build():
    src = open(SRC, encoding='utf-8').read()
    html = open(TPL, encoding='utf-8').read()
    used = set()
    for tok, a, b in QUOTES:
        assert tok not in used, f'duplicate token {tok}'
        used.add(tok)
        frag = slice_quote(src, a, b)
        html = html.replace('{{%s}}' % tok, '<q>' + frag + '</q>')
    # 模板里引用的 token 必须全部被定义
    import re
    leftover = re.findall(r'\{\{(Q\d+)\}\}', html)
    assert not leftover, f'unused template tokens: {sorted(set(leftover))}'
    # Q27/Q28/Q30/Q31/Q46/Q52 页面未直接使用，属备用切片，不注入也不报错
    open(OUT, 'w', encoding='utf-8').write(html)
    print(f'OK: {len(QUOTES)} quote tokens, wrote {OUT}')


if __name__ == '__main__':
    build()
