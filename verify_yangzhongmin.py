for b in blocks:
    b = b.split('<span class="qs">')[0]
    t = norm(re.sub(r"<[^>]+>", "", b))
    if t and t not in book:
        fails.append(f"[页面引文未命中] {t[:34]}…")

# 散文内嵌片段：span class="ys" 之内
